import os
import re
from datetime import datetime, timezone, timedelta

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

load_dotenv()

DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
if not DATABASE_URL:
    raise RuntimeError(
        "DATABASE_URL is missing. Add your Voroa PostgreSQL connection URL to .env."
    )


def now_utc():
    return datetime.now(timezone.utc)


def iso(dt):
    return dt.astimezone(timezone.utc).isoformat()


def parse_dt(value):
    if isinstance(value, datetime):
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value
    return datetime.fromisoformat(value)


def connect():
    return psycopg.connect(DATABASE_URL, row_factory=dict_row)


def init_db():
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    user_id BIGINT PRIMARY KEY,
                    access_expires_at TEXT,
                    monitoring_enabled INTEGER NOT NULL DEFAULT 1,
                    paused_at TEXT
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS keywords (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    keyword TEXT NOT NULL,
                    UNIQUE(user_id, keyword),
                    FOREIGN KEY(user_id) REFERENCES users(user_id)
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS access_codes (
                    code TEXT PRIMARY KEY,
                    created_at TEXT NOT NULL,
                    duration_seconds BIGINT NOT NULL DEFAULT 86400,
                    activated_by BIGINT,
                    activated_at TEXT,
                    expires_at TEXT
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS monitored_chats (
                    chat_id BIGINT PRIMARY KEY,
                    title TEXT NOT NULL,
                    username TEXT,
                    chat_type TEXT,
                    last_seen_at TEXT NOT NULL,
                    admin_monitored INTEGER NOT NULL DEFAULT 0
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS user_monitored_chats (
                    user_id BIGINT NOT NULL,
                    chat_id BIGINT NOT NULL,
                    added_at TEXT NOT NULL,
                    PRIMARY KEY (user_id, chat_id),
                    FOREIGN KEY(user_id) REFERENCES users(user_id),
                    FOREIGN KEY(chat_id) REFERENCES monitored_chats(chat_id)
                )
            """)

            # Safe migrations for databases created by an earlier PostgreSQL version.
            for table, column, definition in [
                ("users", "monitoring_enabled", "INTEGER NOT NULL DEFAULT 1"),
                ("users", "paused_at", "TEXT"),
                ("monitored_chats", "admin_monitored", "INTEGER NOT NULL DEFAULT 0"),
                ("access_codes", "duration_seconds", "BIGINT NOT NULL DEFAULT 86400"),
                ("access_codes", "activated_by", "BIGINT"),
                ("access_codes", "activated_at", "TEXT"),
                ("access_codes", "expires_at", "TEXT"),
            ]:
                cur.execute("""
                    SELECT 1
                    FROM information_schema.columns
                    WHERE table_schema = 'public'
                      AND table_name = %s
                      AND column_name = %s
                """, (table, column))
                if cur.fetchone() is None:
                    cur.execute(
                        f'ALTER TABLE "{table}" ADD COLUMN "{column}" {definition}'
                    )

            cur.execute("UPDATE users SET monitoring_enabled=1 WHERE monitoring_enabled IS NULL")


def ensure_user(user_id):
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                INSERT INTO users(user_id, monitoring_enabled)
                VALUES (%s, 1)
                ON CONFLICT(user_id) DO NOTHING
                """,
                (int(user_id),),
            )


def get_user_expiry(user_id):
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT access_expires_at FROM users WHERE user_id=%s",
                (int(user_id),),
            )
            row = cur.fetchone()
    if not row or not row["access_expires_at"]:
        return None
    return parse_dt(row["access_expires_at"])


def has_active_access(user_id):
    expiry = get_user_expiry(user_id)
    return expiry is not None and expiry > now_utc()


def set_user_access(user_id, expires_at):
    ensure_user(user_id)
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                UPDATE users
                SET access_expires_at=%s, monitoring_enabled=1, paused_at=NULL
                WHERE user_id=%s
                """,
                (iso(expires_at), int(user_id)),
            )


