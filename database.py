def get_customers():
    now = now_utc()
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT
                    u.user_id,
                    u.access_expires_at,
                    u.monitoring_enabled,
                    u.paused_at,
                    COUNT(k.id) AS keyword_count,
                    MAX(ac.activated_at) AS last_activated_at
                FROM users u
                LEFT JOIN keywords k ON k.user_id = u.user_id
                LEFT JOIN access_codes ac ON ac.activated_by = u.user_id
                GROUP BY u.user_id
                ORDER BY
                    CASE
                        WHEN u.access_expires_at IS NOT NULL
                         AND u.access_expires_at > %s
                        THEN 0 ELSE 1
                    END,
                    u.access_expires_at DESC,
                    u.user_id
            """, (iso(now),))
            rows = cur.fetchall()
    return [dict(row) for row in rows]


