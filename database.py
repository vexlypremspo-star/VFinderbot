def pause_monitoring(user_id):
    ensure_user(user_id)
    now = now_utc()
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT access_expires_at, monitoring_enabled, paused_at
                FROM users WHERE user_id=%s
                """,
                (int(user_id),),
            )
            row = cur.fetchone()
            if not row or not row["access_expires_at"]:
                return False, "no_access"
            expiry = parse_dt(row["access_expires_at"])
            if expiry <= now:
                return False, "expired"
            if not bool(row["monitoring_enabled"]):
                return False, "already_paused"
            cur.execute(
                """
                UPDATE users SET monitoring_enabled=0, paused_at=%s
                WHERE user_id=%s
                """,
                (iso(now), int(user_id)),
            )
    return True, "ok"


def resume_monitoring(user_id):
    ensure_user(user_id)
    now = now_utc()
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT access_expires_at, monitoring_enabled, paused_at
                FROM users WHERE user_id=%s
                """,
                (int(user_id),),
            )
            row = cur.fetchone()
            if not row or not row["access_expires_at"]:
                return False, "no_access", None
            expiry = parse_dt(row["access_expires_at"])
            if bool(row["monitoring_enabled"]):
                return False, "already_running", expiry
            paused_at = parse_dt(row["paused_at"]) if row["paused_at"] else None
            if not paused_at:
                return False, "not_paused", expiry
            new_expiry = expiry + (now - paused_at)
            cur.execute(
                """
                UPDATE users
                SET access_expires_at=%s, monitoring_enabled=1, paused_at=NULL
                WHERE user_id=%s
                """,
                (iso(new_expiry), int(user_id)),
            )
    return True, "ok", new_expiry


def add_keyword(user_id, keyword):
    ensure_user(user_id)
    keyword = keyword.strip()
    if not keyword:
        return False
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                INSERT INTO keywords(user_id, keyword)
                VALUES (%s, %s)
                ON CONFLICT(user_id, keyword) DO NOTHING
                """,
                (int(user_id), keyword),
            )
            return cur.rowcount > 0


def remove_keyword(user_id, keyword):
    keyword = keyword.strip()
    if not keyword:
        return False
    with connect() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                DELETE FROM keywords
                WHERE user_id=%s AND LOWER(keyword)=LOWER(%s)
                """,
                (int(user_id), keyword),
            )
            return cur.rowcount > 0


